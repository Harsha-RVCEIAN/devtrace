#!/usr/bin/env bash
# scripts/install_hook.sh
#
# Purpose:
#     Installs or uninstalls the DevTrace automatic commit ingestion
#     post-commit hook in .git/hooks/post-commit.
#
# Usage:
#     # Install with defaults (or specific project/user UUIDs):
#     ./scripts/install_hook.sh <PROJECT_UUID> <USER_UUID> [API_URL]
#
#     # Uninstall hook:
#     ./scripts/install_hook.sh --uninstall

set -euo pipefail

REPO_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
HOOK_PATH="$REPO_ROOT/.git/hooks/post-commit"

if [[ "${1:-}" == "--uninstall" ]]; then
    if [[ -f "$HOOK_PATH" ]]; then
        rm -f "$HOOK_PATH"
        echo "Successfully uninstalled DevTrace post-commit hook from: $HOOK_PATH"
    else
        echo "No post-commit hook found at: $HOOK_PATH"
    fi
    exit 0
fi

PROJECT_ID="${1:-d3b07384-d113-4c92-b0b2-320d9f4c3912}"
USER_ID="${2:-a0eebc99-9c0b-4ef8-bb6d-6bb9bd380a11}"
API_URL="${3:-http://localhost:8000/commits}"

mkdir -p "$REPO_ROOT/.git/hooks"

cat <<EOF > "$HOOK_PATH"
#!/usr/bin/env bash
# Auto-generated by DevTrace Hook Installer
# Triggers background Git commit and diff ingestion to the DevTrace API

python3 -m integrations.git.collector \\
    --repo-path "$REPO_ROOT" \\
    --project-id "$PROJECT_ID" \\
    --user-id "$USER_ID" \\
    --api-url "$API_URL" > /dev/null 2>&1 &
EOF

chmod +x "$HOOK_PATH"

echo "=========================================================="
echo " DevTrace Git Ingestion Hook Successfully Installed"
echo "=========================================================="
echo " Hook Path:   $HOOK_PATH"
echo " Target Repo: $REPO_ROOT"
echo " Project ID:  $PROJECT_ID"
echo " User ID:     $USER_ID"
echo " API URL:     $API_URL"
echo ""
echo " Every 'git commit' will now automatically ingest diffs to PostgreSQL."
echo " To disable: ./scripts/install_hook.sh --uninstall"
echo "=========================================================="
