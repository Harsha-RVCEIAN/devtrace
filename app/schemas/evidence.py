
"""
Pydantic schemas for decision evidence.

Evidence records the source material supporting a software engineering
decision. Each evidence record belongs to an existing decision.

The evidence type and source reference are required by the SQLAlchemy model.
The capture timestamp is generated by the database by default, but the
response schema always includes it.
"""

from datetime import datetime
from uuid import UUID

from pydantic import BaseModel, ConfigDict, Field, field_validator


class EvidenceCreate(BaseModel):
    """
    Request schema for adding evidence to a decision.

    Attributes:
        evidence_type: Category of supporting material, such as
            'research_paper', 'benchmark', 'code_review', or 'documentation'.
        source_reference: URL, document identifier, repository reference,
            or another locator that identifies the supporting material.
    """

    model_config = ConfigDict(extra="forbid")

    evidence_type: str = Field(
        min_length=1,
        max_length=80,
        description="Category of the supporting evidence.",
    )

    source_reference: str = Field(
        min_length=1,
        max_length=2000,
        description="Reference locating the supporting evidence.",
    )

    @field_validator("evidence_type")
    @classmethod
    def validate_evidence_type(cls, value: str) -> str:
        """Reject empty or whitespace-only evidence categories."""
        value = value.strip()

        if not value:
            raise ValueError("Evidence type cannot be blank.")

        return value

    @field_validator("source_reference")
    @classmethod
    def validate_source_reference(cls, value: str) -> str:
        """
        Validate and normalize the evidence locator.

        This accepts more than URLs because evidence may also be identified
        by a commit hash, document ID, issue number, or internal reference.
        """
        value = value.strip()

        if not value:
            raise ValueError("Evidence source reference cannot be blank.")

        return value


class EvidenceResponse(BaseModel):
    """
    Response schema for evidence retrieved from the database.

    The evidence ID and capture timestamp are generated by the database
    model/defaults; clients do not supply them when creating evidence.
    """

    model_config = ConfigDict(from_attributes=True)

    evidence_id: UUID
    decision_id: UUID
    evidence_type: str
    source_reference: str
    captured_at: datetime
